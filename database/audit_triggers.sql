CREATE OR REPLACE TRIGGER TRG_AUDITORIA_RUTA_PLANIFICADA
AFTER INSERT OR UPDATE OR DELETE ON RUTA_PLANIFICADA
FOR EACH ROW
DECLARE
  V_ACCION VARCHAR2(100);
  V_ID_RUTA RUTA_PLANIFICADA.ID_RUTA%TYPE;
BEGIN
  IF INSERTING THEN
    V_ACCION := 'INSERT';
    V_ID_RUTA := :NEW.ID_RUTA;
  ELSIF UPDATING THEN
    V_ACCION := 'UPDATE';
    V_ID_RUTA := :NEW.ID_RUTA;
  ELSE
    V_ACCION := 'DELETE';
    V_ID_RUTA := :OLD.ID_RUTA;
  END IF;

  INSERT INTO AUDITORIA_RUTAS (
    FECHA_ACCION,
    USUARIO_ORACLE,
    ACCION,
    ID_RUTA,
    ESTADO_ANTERIOR,
    ESTADO_NUEVO
  )
  VALUES (
    LOCALTIMESTAMP,
    USER,
    V_ACCION,
    V_ID_RUTA,
    NULL,
    NULL
  );
END;
/

CREATE OR REPLACE TRIGGER TRG_AUDITORIA_EMPLEADO
AFTER INSERT OR UPDATE OR DELETE ON EMPLEADO
FOR EACH ROW
DECLARE
  V_ACCION VARCHAR2(20);
  V_RUN_EMPLEADO EMPLEADO.RUN%TYPE;
  V_DETALLE VARCHAR2(500);
  V_NOMBRE_ANTERIOR VARCHAR2(300);
  V_NOMBRE_NUEVO VARCHAR2(300);
BEGIN
  IF UPDATING OR DELETING THEN
    V_NOMBRE_ANTERIOR := TRIM(
      NVL(:OLD.PNOMBRE, '') || ' ' ||
      NVL(:OLD.SNOMBRE, '') || ' ' ||
      NVL(:OLD.APPATERNO, '') || ' ' ||
      NVL(:OLD.APMATERNO, '')
    );
  END IF;

  IF INSERTING OR UPDATING THEN
    V_NOMBRE_NUEVO := TRIM(
      NVL(:NEW.PNOMBRE, '') || ' ' ||
      NVL(:NEW.SNOMBRE, '') || ' ' ||
      NVL(:NEW.APPATERNO, '') || ' ' ||
      NVL(:NEW.APMATERNO, '')
    );
  END IF;

  IF INSERTING THEN
    V_ACCION := 'INSERT';
    V_RUN_EMPLEADO := :NEW.RUN;
    V_DETALLE := 'Se registró el empleado: ' || V_NOMBRE_NUEVO;
  ELSIF UPDATING THEN
    V_ACCION := 'UPDATE';
    V_RUN_EMPLEADO := :NEW.RUN;
    V_DETALLE := 'Se actualizaron los datos del empleado. Nombre anterior: ' ||
      V_NOMBRE_ANTERIOR || '. Nombre nuevo: ' || V_NOMBRE_NUEVO;
  ELSE
    V_ACCION := 'DELETE';
    V_RUN_EMPLEADO := :OLD.RUN;
    V_DETALLE := 'Se eliminó el empleado: ' || V_NOMBRE_ANTERIOR;
  END IF;

  INSERT INTO AUDITORIA_EMPLEADO (
    FECHA_ACCION,
    USUARIO_ORACLE,
    ACCION,
    RUN_EMPLEADO,
    DETALLE_CAMBIO
  )
  VALUES (
    LOCALTIMESTAMP,
    USER,
    V_ACCION,
    V_RUN_EMPLEADO,
    SUBSTR(V_DETALLE, 1, 500)
  );
END;
/

CREATE OR REPLACE TRIGGER TRG_AUDITORIA_VEHICULO
AFTER INSERT OR UPDATE OR DELETE ON VEHICULO
FOR EACH ROW
DECLARE
  V_ACCION VARCHAR2(20);
  V_ID_VEHICULO VEHICULO.ID_VEHICULO%TYPE;
  V_PATENTE VEHICULO.PATENTE%TYPE;
  V_DETALLE VARCHAR2(500);
BEGIN
  IF INSERTING THEN
    V_ACCION := 'INSERT';
    V_ID_VEHICULO := :NEW.ID_VEHICULO;
    V_PATENTE := :NEW.PATENTE;
    V_DETALLE := 'Se registró un nuevo vehículo (' || :NEW.MARCA || ' ' || :NEW.MODELO || ')';
  ELSIF UPDATING THEN
    V_ACCION := 'UPDATE';
    V_ID_VEHICULO := :NEW.ID_VEHICULO;
    V_PATENTE := :NEW.PATENTE;
    V_DETALLE := 'Se actualizaron los datos del vehículo.';
  ELSE
    V_ACCION := 'DELETE';
    V_ID_VEHICULO := :OLD.ID_VEHICULO;
    V_PATENTE := :OLD.PATENTE;
    V_DETALLE := 'Se eliminó el vehículo (' || :OLD.MARCA || ' ' || :OLD.MODELO || ')';
  END IF;

  INSERT INTO AUDITORIA_VEHICULO (
    FECHA_ACCION,
    USUARIO_ORACLE,
    ACCION,
    ID_VEHICULO,
    PATENTE,
    DETALLE_CAMBIO
  )
  VALUES (
    LOCALTIMESTAMP,
    USER,
    V_ACCION,
    V_ID_VEHICULO,
    V_PATENTE,
    V_DETALLE
  );
END;
/

ALTER TRIGGER TRG_AUDITORIA_RUTA_PLANIFICADA ENABLE;
ALTER TRIGGER TRG_AUDITORIA_EMPLEADO ENABLE;
ALTER TRIGGER TRG_AUDITORIA_VEHICULO ENABLE;

SELECT TRIGGER_NAME, STATUS
FROM USER_TRIGGERS
WHERE TRIGGER_NAME IN (
  'TRG_AUDITORIA_RUTA_PLANIFICADA',
  'TRG_AUDITORIA_EMPLEADO',
  'TRG_AUDITORIA_VEHICULO'
)
ORDER BY TRIGGER_NAME;

SELECT NAME, TYPE, LINE, TEXT
FROM USER_ERRORS
WHERE NAME IN (
  'TRG_AUDITORIA_RUTA_PLANIFICADA',
  'TRG_AUDITORIA_EMPLEADO',
  'TRG_AUDITORIA_VEHICULO'
)
ORDER BY NAME, SEQUENCE;
